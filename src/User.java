
public class User {
	
	  private int id ; 
	  private String Name ; 
	  private String Email ;
	  private String numberPhone ;
	  
	  
	  public User(int id, String name, String email, String numberPhone) {
		super();
		this.id = id;
		Name = name;
		Email = email;
		this.numberPhone = numberPhone;
	  } 
	  
	  
	  
	
}
